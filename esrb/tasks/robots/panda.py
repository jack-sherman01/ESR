"""Shared Panda binding, bounded joint commands and differential IK.

Only reset-time initialization writes joint positions. During a rollout every
robot motion is generated by the native actuators and mj_step.
"""
from pathlib import Path
import xml.etree.ElementTree as ET

import mujoco
import numpy as np

ROBOT_XML = Path(__file__).parent / 'assets/panda.xml'
HOME = np.array([0., -.25, 0., -1.8, 0., 1.6, 2.3562])


def robot_tree():
    root = ET.parse(ROBOT_XML).getroot()
    for mesh in root.findall('asset/mesh'):
        mesh.set('file', str((ROBOT_XML.parent / mesh.get('file')).resolve()))
    return root


def orientation_error(current, target):
    return .5 * sum((np.cross(current[:, i], target[:, i]) for i in range(3)), np.zeros(3))


def yaw_rotation(angle):
    c, s = np.cos(angle), np.sin(angle)
    return np.array([[c, -s, 0.], [s, c, 0.], [0., 0., 1.]])


def joint_target(info, position, rotation, closure, *, step=.035):
    jac = np.asarray(info['target_grip_jacobian']).copy()
    error = np.r_[np.asarray(position)-info['target_grip_position'],
                  .25*orientation_error(np.asarray(info['target_grip_rotation']), rotation)]
    jac[3:] *= .25
    inverse = jac.T @ np.linalg.solve(jac @ jac.T+.0001*np.eye(6), np.eye(6))
    q = np.asarray(info['arm_joint_targets'])
    null = (np.eye(7)-inverse @ jac) @ (.002*(np.asarray(info['arm_home'])-q))
    delta = np.clip(inverse @ error+null, -step, step)
    limits = np.asarray(info['arm_joint_limits'])
    return np.r_[np.clip(q+delta, limits[:, 0]+.01, limits[:, 1]-.01), closure]


class PandaRobot:
    def __init__(self, model, data):
        self.model, self.data = model, data
        joints = [model.joint(f'joint{i}').id for i in range(1, 8)]
        self.joints = np.array(joints)
        self.q = model.jnt_qposadr[joints]
        self.v = model.jnt_dofadr[joints]
        self.limits = model.jnt_range[joints].copy()
        self.site = model.site('grip_origin').id
        self.fingers = [model.jnt_qposadr[model.joint(f'finger_joint{i}').id] for i in (1, 2)]
        self.command_data = mujoco.MjData(model)
        self.pad_groups = [{i for i in range(model.ngeom) if model.geom_bodyid[i] == model.body(side+'_finger').id
                            and (model.geom_contype[i] or model.geom_conaffinity[i])}
                           for side in ('left', 'right')]
        self.pads = set.union(*self.pad_groups)
        self.geoms = {i for i in range(model.ngeom) if model.geom(i).name.startswith('panda_')} | self.pads

    def initialize(self, target=(0., -.14, .32)):
        d, m = self.data, self.model
        q = HOME.copy()
        d.qpos[self.fingers] = .04
        for _ in range(400):
            d.qpos[self.q] = q
            mujoco.mj_forward(m, d)
            error = np.r_[np.array(target)-d.site_xpos[self.site],
                          .25*orientation_error(d.site_xmat[self.site].reshape(3, 3), np.eye(3))]
            if np.linalg.norm(error) < 1e-5:
                break
            jp, jr = np.zeros((3, m.nv)), np.zeros((3, m.nv))
            mujoco.mj_jacSite(m, d, jp, jr, self.site)
            j = np.vstack((jp[:, self.v], .25*jr[:, self.v]))
            dq = j.T @ np.linalg.solve(j @ j.T+.0001*np.eye(6), error)
            q = np.clip(q+np.clip(dq, -.1, .1), self.limits[:, 0]+.03, self.limits[:, 1]-.03)
        else:
            raise RuntimeError('Panda initial IK unavailable')
        d.qpos[self.q], d.qvel[:] = q, 0.
        d.ctrl[:8] = np.r_[q, 255.]
        self.home = q.copy()
        mujoco.mj_forward(m, d)

    def information(self):
        m, d, t = self.model, self.data, self.command_data
        t.qpos[:] = d.qpos
        t.qpos[self.q] = d.ctrl[:7]
        mujoco.mj_kinematics(m, t)
        mujoco.mj_comPos(m, t)
        jp, jr = np.zeros((3, m.nv)), np.zeros((3, m.nv))
        mujoco.mj_jacSite(m, t, jp, jr, self.site)
        return {'arm_joint_targets': d.ctrl[:7].tolist(), 'arm_joint_limits': self.limits.tolist(),
                'arm_home': self.home.tolist(), 'target_grip_position': t.site_xpos[self.site].tolist(),
                'target_grip_rotation': t.site_xmat[self.site].reshape(3, 3).tolist(),
                'target_grip_jacobian': np.vstack((jp[:, self.v], jr[:, self.v])).tolist(),
                'grip_position': d.site_xpos[self.site].tolist(),
                'grip_rotation': d.site_xmat[self.site].reshape(3, 3).tolist()}

    def apply(self, action):
        action = np.asarray(action, dtype=float)
        if action.shape != (8,) or not np.isfinite(action).all():
            raise ValueError('Panda action must contain seven finite joint targets and closure')
        opening = np.clip(.04-action[7], 0., .04)
        previous = self.data.ctrl[7]/255*.04
        opening = previous+np.clip(opening-previous, -.0006, .0006)
        self.data.ctrl[:8] = np.r_[np.clip(action[:7], self.limits[:, 0], self.limits[:, 1]), opening/.04*255]
